"""The paper's benchmark table, CalicoST against `run_cnaster_port --sal` on CalicoST's benchmark fixture.

    run_study --benchmark-table [--root DIR] [--repeats 3] [--out docs/benchmark.tex]
    run_study --benchmark-table --supported [--out docs/supported.tex]

draws `fixtures.R0_MANIFEST` r0 (`dev_tree` 60 x 50) into `ROOT` and refuses
it unless it hashes to `fixtures.R0_HASH` (`3381575a`), then writes `OUT`:

- **CalicoST**: its committed outputs (`tests/data/benchmarks/dev_tree_r0/
  calicost.tar.xz`, c1abcae, `n_clones 5`, uncapped; #532), scored by
  `port.qa.audit.score_sample` against the draw. Its runtime is the archive's
  `run.json` wall, 3 cores. It is not rerun: it took 20,243 s.
- **port**: `run_audit --sim -- --sal --no-plots` at the current commit
  (`port.qa.benchmark.port`), the median wall of `--repeats` runs. The
  tree must be clean, so the commit names the code that ran.

Columns: the method, or the fixture's `short` name, in a column `SHORT`
`\\texttt` characters wide in both tables so they set alike; the fixture's
hash; clone ARI on the fitted clones (R) and after the integer merge (N);
copy-state ARI of the HMM state (R) and of the decoded integer `(A, B)`,
phase-free (N, `copy_ari_pf`); CNA, phase-free (`exact_altered_minor`), the
share of altered clone-bins decoded to their planted `(A, B)` or `(B, A)`;
and the wall in minutes. `(A, B)` and `(B, A)` are one state in both phase-free
columns, as the paper's integer copy number is. The macros (`\\tablesize`,
`\\calicost`, `\\cnamaste`, `\\mathbbm`) are the paper's.

`--supported` writes the same table for port alone, one row per fixture of
the ledger's latest benchmark sweep (`port.qa.ledger.last_benchmark`,
`docs/metrics/fixtures.md`'s supported fixtures), from its recorded metrics:
nothing is rerun, and the commit and sal pin are the sweep's.
"""

from __future__ import annotations

import argparse
import json
import tarfile
import tempfile
from dataclasses import asdict
from pathlib import Path
from typing import Any

from port.extensions.repository import ROOT

ARCHIVE = ROOT / "tests" / "data" / "benchmarks" / "dev_tree_r0" / "calicost.tar.xz"
OUT = ROOT / "docs" / "benchmark.tex"
CNASTER = (
    ROOT / "tests" / "data" / "benchmarks" / "dev_tree_r0_cnaster" / "cnaster.tar.xz"
)
CNASTER_OUT = ROOT / "docs" / "benchmark_cnaster.tex"
SUPPORTED_OUT = ROOT / "docs" / "supported.tex"

TEMPLATE = r"""% Generated by `run_study --benchmark-table{mode}` at port {commit}, sal {sal}: do not edit.
% {note}
\begin{{table}}[!t]
\centering
\begin{{threeparttable}}
\tablesize
\setlength{{\tabcolsep}}{{0pt}}
\begin{{tabular*}}{{\linewidth}}{{@{{}}ll@{{\extracolsep{{\fill}}}}rrrrrr@{{}}}}
\toprule
{first}\phantom{{\texttt{{{width}}}}} & Hash & \multicolumn{{4}}{{c}}{{ARI}} & CNA & Runtime \\
\cmidrule(lr){{3-6}}
 & & $\mathbbm{{R}}$-clone & $\mathbbm{{N}}$-clone & $\mathbbm{{R}}$-copy-state & $\mathbbm{{N}}$-copy-state & & {{[}}mins{{]}} \\
 & &                     &                     &              &              & &            \\
\midrule
{rows}
\bottomrule

\end{{tabular*}}
\end{{threeparttable}}
\label{{tab:{label}}}
\end{{table}}
"""

ROW = r"{name:<30} & \texttt{{{digest}}} & {ari} & {ari_integer} & {state_ari} & {copy_ari_pf} & {exact_altered_minor} & {minutes:>10} \\"
"""One row, a method or fixture and its fixture's hash; the values are `half_up`'s strings."""

SHORT = 25
"""The name column's width in `\\texttt` characters, both tables': room for names past `tree_1s_dense`'s 13."""

SCORES = ("ari", "ari_integer", "state_ari", "copy_ari_pf", "exact_altered_minor")


def half_up(value: float, places: int) -> str:
    """`value` to `places` decimals, half away from zero on its shortest decimal form, as the paper rounds (0.9075 is 0.908)."""
    from decimal import ROUND_HALF_UP, Decimal

    return str(
        Decimal(repr(float(value))).quantize(
            Decimal(1).scaleb(-places), rounding=ROUND_HALF_UP
        )
    )


def drawn(root: Path) -> Path:
    """`R0_MANIFEST` r0 under `root`, drawn if absent; refused unless it hashes to `R0_HASH`."""
    import subprocess
    import sys

    from port.sim.fixtures import R0_HASH, R0_MANIFEST, realization_hash

    found = sorted(root.glob("*/r0"))
    if not found:
        subprocess.run([sys.executable, "-m", "port.sim.draw", str(ROOT / R0_MANIFEST), "--into", str(root)],
                       check=True, capture_output=True)  # fmt: skip
        found = sorted(root.glob("*/r0"))
    path = found[0].resolve()
    digest = realization_hash(path)
    if digest != R0_HASH:
        msg = f"{path} hashes to {digest}, not {R0_HASH}: not CalicoST's benchmark fixture"
        raise RuntimeError(msg)
    return path


def calicost_row(path: Path) -> dict[str, Any]:
    """CalicoST's committed outputs, scored against the draw at `path`; the archive's wall."""
    return _archived(path, ARCHIVE, "calicost")


def cnaster_row(path: Path) -> dict[str, Any]:
    """`cnaster` at its pin, #105's row alone rebound (T- #833): its committed outputs scored against the draw at `path`; the archive's wall."""
    return _archived(path, CNASTER, "cnaster")


def _archived(path: Path, tarball: Path, arm: str) -> dict[str, Any]:
    """`tarball`'s `arm/` outputs scored by `score_sample` against the draw at `path`, with its `run.json` wall and cores."""
    from port.qa.audit import score_sample
    from port.sim.fixtures import load_simulated

    sample = load_simulated(path.name, path.parent)
    with tempfile.TemporaryDirectory() as scratch:
        with tarfile.open(tarball) as archive:
            archive.extractall(scratch, filter="data")
        output = Path(scratch) / arm
        run = json.loads((output / "run.json").read_text())
        scored = asdict(score_sample(sample, output, arm, float(run["wall_s"])))
    return {
        **scored,
        "wall": float(run["wall_s"]),
        "cores": int(run["cores"]),
        "commit": str(run.get("commit", "")),
    }


def port_row(path: Path, repeats: int) -> dict[str, Any]:
    """`run_cnaster_port --sal` on the draw at `path`, `repeats` times: the median wall."""
    import os

    from port.qa.benchmark import port

    return {**port(str(path), repeats), "cores": os.cpu_count() or 0}


def short(fixture: str) -> str:
    """`fixture`'s name in the table, `dev_` and `_r0` dropped: at most `SHORT` characters, its hash the column beside."""
    name = fixture.removeprefix("dev_").removesuffix("_r0")
    if len(name) > SHORT:
        msg = f"{fixture} shortens to {name}, over {SHORT} characters"
        raise ValueError(msg)
    return name


def _rows(rows: list[tuple[str, str, dict[str, Any]]]) -> str:
    """`ROW` per `(name, hash, scores)`: three decimals half up, minutes to one."""
    return "\n".join(
        ROW.format(
            name=name,
            digest=digest,
            minutes=half_up(row["wall"] / 60.0, 1),
            **{k: half_up(row[k], 3) for k in SCORES},
        )  # fmt: skip
        for name, digest, row in rows
    )


def render(calicost: dict[str, Any], port: dict[str, Any], *, fixture: str, commit: str, sal: str,
           repeats: int, cnaster: dict[str, Any] | None = None) -> str:  # fmt: skip
    """The paper's table: CalicoST and port on `fixture`, and `cnaster` between them where given (T- #833)."""
    note = (f"CalicoST c1abcae from its committed outputs ({calicost['cores']} cores); "
            f"port --sal, median of {repeats} on {port['cores']} cores.")  # fmt: skip
    rows = [(r"\calicost{}", fixture, calicost), (r"\cnamaste{}", fixture, port)]
    if cnaster is not None:
        rows.insert(1, (r"\cnaster{}", fixture, cnaster))
        note += (f" cnaster {cnaster['commit'][:7]}, #105's row alone rebound, from its committed outputs "
                 f"({cnaster['cores']} cores).")  # fmt: skip
    return TEMPLATE.format(rows=_rows(rows), mode=" --cnaster" if cnaster is not None else "",
                           first="Method", width="x" * SHORT, label="benchmark", note=note,
                           commit=commit, sal=sal)  # fmt: skip


LEDGER_SCORES = {"clone_ari": "ari", "clone_ari_int": "ari_integer", "state_ari": "state_ari",
                 "copy_ari_pf": "copy_ari_pf", "exact_altered_pf": "exact_altered_minor", "wall_s": "wall"}  # fmt: skip
"""The ledger's metric for each of `SCORES` and the wall (`port.qa.ledger.METRICS`)."""


def swept() -> tuple[str, list[tuple[str, str, dict[str, float]]]]:
    """The latest benchmark sweep's commit, and per run its fixture, hash and `LEDGER_SCORES`."""
    from port.qa import ledger

    runs = ledger.last_benchmark()
    if not runs:
        msg = "the ledger holds no benchmark sweep"
        raise RuntimeError(msg)
    lines = ledger.ledger()
    out = []
    for run in runs:
        mine = [line for line in lines if line["run_id"] == run["run_id"]]
        scores = {LEDGER_SCORES[line["metric"]]: float(line["value"]) for line in mine
                  if line["metric"] in LEDGER_SCORES}  # fmt: skip
        out.append((mine[0]["fixture"], mine[0]["fixture_hash"], scores))
    return runs[0]["commit"], out


def render_supported(
    rows: list[tuple[str, str, dict[str, float]]], *, commit: str, sal: str
) -> str:
    """port's table over the supported fixtures, one row per fixture: its `short` name, and its hash beside."""
    named = [(rf"\texttt{{{short(fixture).replace('_', chr(92) + '_')}}}", digest, scores)
             for fixture, digest, scores in rows]  # fmt: skip
    note = "port --sal, one run per fixture, serial on an idle host (docs/metrics/fixtures.md)."
    return TEMPLATE.format(rows=_rows(named), mode=" --supported", first="Fixture", width="x" * SHORT, label="supported",
                           note=note, commit=commit, sal=sal)  # fmt: skip


def sal_pin(commit: str | None = None) -> str:
    """The `snakes_and_ladders` commit `uv.lock` pins, to 8 hex: the working tree's, or at `commit`."""
    import subprocess

    text = ((ROOT / "uv.lock").read_text() if commit is None else
            subprocess.run(["git", "show", f"{commit}:uv.lock"], cwd=ROOT, capture_output=True,
                           text=True, check=True).stdout)  # fmt: skip
    for line in text.splitlines():
        if "snakes_and_ladders" in line and "#" in line:
            return line.rsplit("#", 1)[1].strip('" }')[:8]
    msg = "uv.lock pins no snakes_and_ladders commit"
    raise RuntimeError(msg)


def main(argv: list[str] | None = None) -> int:
    from port.qa import provenance
    from port.sim.fixtures import R0_HASH

    parser = argparse.ArgumentParser(
        prog="run_study --benchmark-table", description=(__doc__ or "").splitlines()[0]
    )
    parser.add_argument(
        "--root", type=Path, default=ROOT / ".cache" / "benchmarks" / "benchmark_table"
    )
    parser.add_argument("--repeats", type=int, default=3)
    parser.add_argument(
        "--out",
        type=Path,
        default=None,
        help=f"default {OUT}, or {SUPPORTED_OUT} with --supported",
    )
    parser.add_argument("--supported", action="store_true",
                        help="port's table over the latest benchmark sweep's fixtures, from the ledger")  # fmt: skip
    parser.add_argument("--cnaster", action="store_true",
                        help=f"add cnaster's committed row (T- #833); default --out {CNASTER_OUT}")  # fmt: skip
    parser.add_argument(
        "--dirty",
        action="store_true",
        help="run on an uncommitted tree; the commit is marked +",
    )
    arguments = parser.parse_args(argv)

    if arguments.supported:
        out = arguments.out or SUPPORTED_OUT
        commit, rows = swept()
        out.write_text(render_supported(rows, commit=commit, sal=sal_pin(commit)))
        print(out.read_text())
        return 0
    arguments.out = arguments.out or (CNASTER_OUT if arguments.cnaster else OUT)

    dirty = provenance.dirty(*provenance.INPUTS, untracked=True)
    if dirty and not arguments.dirty:
        print("inputs are uncommitted; commit them, or pass --dirty")
        return 1
    commit = provenance.head() + ("+" if dirty else "")

    path = drawn(arguments.root)
    calicost = calicost_row(path)
    cnaster = cnaster_row(path) if arguments.cnaster else None
    port = port_row(path, arguments.repeats)
    arguments.out.write_text(render(calicost, port, fixture=R0_HASH, commit=commit, sal=sal_pin(),
                                    repeats=arguments.repeats, cnaster=cnaster))  # fmt: skip
    print(arguments.out.read_text())
    return 0
