"""`port.studies.benchmark_table`: the paper's CalicoST against port table on `3381575a`."""

from __future__ import annotations

from pathlib import Path

import pytest

CALICOST = {"ari": 0.8538, "ari_integer": 0.8538, "state_ari": 0.0889, "copy_ari_pf": 0.9075,
            "exact_altered_minor": 0.7095, "wall": 20243.0, "cores": 3}  # fmt: skip
"""#532's CalicoST row (`docs/calicost-benchmark.md`), phase-free."""

PORT = {"ari": 0.8612, "ari_integer": 1.0, "state_ari": 0.0682, "copy_ari_pf": 0.9829,
        "exact_altered_minor": 0.9348, "wall": 153.6, "cores": 4}  # fmt: skip
"""The committed port archive (`tests/data/benchmarks/dev_tree_r0/port.tar.xz`, 95940e5) scored phase-free."""


@pytest.mark.snapshot
def test_the_table_reproduces_the_papers_rows() -> None:
    """The two archives' rows, phase-free: three decimals half up, minutes to one, the fixture's hash in the header."""
    from port.studies.benchmark_table import render

    tex = render(
        CALICOST, PORT, fixture="3381575a", commit="abc1234", sal="5d59752c", repeats=3
    )

    assert r"Method (\texttt{3381575a})" in tex
    assert (
        r"\calicost{}                  & 0.854 & 0.854 & 0.089 & 0.908 & 0.710 &      337.4 \\"
        in tex
    )
    assert (
        r"\cnamaste{}                  & 0.861 & 1.000 & 0.068 & 0.983 & 0.935 &        2.6 \\"
        in tex
    )
    assert tex.startswith(
        "% Generated by `run_study --benchmark-table` at port abc1234, sal 5d59752c"
    )


@pytest.mark.snapshot
def test_the_cnaster_row_sits_between_and_names_its_pin() -> None:
    """`--cnaster` (T- #833): a `\\cnaster{}` row between CalicoST and port, its commit and cores in the note."""
    from port.studies.benchmark_table import render

    cnaster = PORT | {"wall": 600.0, "cores": 4, "commit": "4adad4d829ac"}
    without = render(
        CALICOST, PORT, fixture="3381575a", commit="abc1234", sal="5d59752c", repeats=3
    )
    tex = render(CALICOST, PORT, fixture="3381575a", commit="abc1234", sal="5d59752c", repeats=3,
                 cnaster=cnaster)  # fmt: skip

    names = [line.split("&")[0].strip() for line in tex.splitlines() if " & 0." in line]
    assert names == [r"\calicost{}", r"\cnaster{}", r"\cnamaste{}"]
    assert (
        r"\cnaster{}                   & 0.861 & 1.000 & 0.068 & 0.983 & 0.935 &       10.0 \\"
        in tex
    )
    assert (
        "cnaster 4adad4d, #105's row alone rebound, from its committed outputs (4 cores)."
        in tex
    )
    assert tex.startswith("% Generated by `run_study --benchmark-table --cnaster`")
    assert "cnaster" not in without.replace("cnamaste", "")


@pytest.mark.snapshot
def test_the_sal_pin_is_the_lockfiles() -> None:
    """`sal_pin` reads the 8-hex commit `uv.lock` pins `snakes_and_ladders` to."""
    from port.extensions.repository import ROOT
    from port.studies.benchmark_table import sal_pin

    pinned = sal_pin()
    assert len(pinned) == 8
    assert f"snakes_and_ladders?branch=main#{pinned}" in (ROOT / "uv.lock").read_text()


